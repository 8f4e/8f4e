#!/usr/bin/env node
/* global console, process */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const contributorLabel = 'contributor';
const contributorsPerRow = 4;
const startMarker = '<!-- CONTRIBUTORS-GRID:START -->';
const endMarker = '<!-- CONTRIBUTORS-GRID:END -->';
const workspaceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const readmePath = path.resolve(workspaceRoot, 'README.md');

await main();

async function main() {
	const repository = process.env.GITHUB_REPOSITORY || getCurrentRepository();
	const pullRequests = getMergedContributorPullRequests(repository);
	const contributors = summarizeContributors(pullRequests);
	const readme = await fs.readFile(readmePath, 'utf8');
	const updatedReadme = replaceGeneratedSection(readme, renderContributorGrid(repository, contributors));

	if (updatedReadme === readme) {
		console.log(`Contributor grid is already up to date for ${repository}.`);
		return;
	}

	await fs.writeFile(readmePath, updatedReadme);
	console.log(`Updated README.md with ${contributors.length} contributors from ${pullRequests.length} merged PRs.`);
}

function getCurrentRepository() {
	return runGh(['repo', 'view', '--json', 'nameWithOwner', '--jq', '.nameWithOwner']).trim();
}

function getMergedContributorPullRequests(repository) {
	const output = runGh([
		'pr',
		'list',
		'--repo',
		repository,
		'--state',
		'merged',
		'--label',
		contributorLabel,
		'--limit',
		'1000',
		'--json',
		'author,number,url',
	]);

	return JSON.parse(output);
}

function runGh(args) {
	try {
		return execFileSync('gh', args, {
			cwd: workspaceRoot,
			encoding: 'utf8',
			maxBuffer: 10 * 1024 * 1024,
			stdio: ['ignore', 'pipe', 'inherit'],
		});
	} catch (error) {
		throw new Error(`GitHub CLI command failed: gh ${args.join(' ')}`, { cause: error });
	}
}

function summarizeContributors(pullRequests) {
	const contributorsByLogin = new Map();

	for (const pullRequest of pullRequests) {
		const author = pullRequest.author;
		if (!author?.login || author.is_bot) {
			continue;
		}

		const key = author.login.toLowerCase();
		const contributor = contributorsByLogin.get(key) ?? {
			login: author.login,
			name: author.name?.trim() || author.login,
			pullRequestCount: 0,
		};
		contributor.pullRequestCount += 1;
		contributorsByLogin.set(key, contributor);
	}

	return [...contributorsByLogin.values()].sort(
		(left, right) =>
			right.pullRequestCount - left.pullRequestCount ||
			left.name.localeCompare(right.name, 'en', { sensitivity: 'base' }) ||
			left.login.localeCompare(right.login, 'en', { sensitivity: 'base' })
	);
}

function renderContributorGrid(repository, contributors) {
	if (contributors.length === 0) {
		return '<p>No community pull requests have been merged yet.</p>';
	}

	const rows = [];
	for (let index = 0; index < contributors.length; index += contributorsPerRow) {
		const cells = contributors.slice(index, index + contributorsPerRow).map(contributor => {
			const profileUrl = `https://github.com/${encodeURIComponent(contributor.login)}`;
			const avatarUrl = `${profileUrl}.png?size=96`;
			const pullRequestSearchUrl = getContributorPullRequestSearchUrl(repository, contributor.login);
			const pullRequestLabel = `🔀 ${contributor.pullRequestCount}`;

			return [
				'<td align="center" valign="top" width="25%">',
				`<a href="${profileUrl}"><img src="${avatarUrl}" width="72" alt="@${escapeHtml(contributor.login)}"><br><sub><b>${escapeHtml(contributor.name)}</b></sub></a><br>`,
				`<sub><a href="${pullRequestSearchUrl}">${pullRequestLabel}</a></sub>`,
				'</td>',
			].join('\n');
		});
		rows.push(`<tr>\n${cells.join('\n')}\n</tr>`);
	}

	return `<!-- Generated by scripts/update-contributors.mjs. -->\n<table>\n${rows.join('\n')}\n</table>`;
}

function getContributorPullRequestSearchUrl(repository, login) {
	const query = `is:pr is:merged label:${contributorLabel} author:${login}`;
	return `https://github.com/${repository}/pulls?q=${encodeURIComponent(query)}`;
}

function escapeHtml(value) {
	return value
		.replaceAll('&', '&amp;')
		.replaceAll('<', '&lt;')
		.replaceAll('>', '&gt;')
		.replaceAll('"', '&quot;')
		.replaceAll("'", '&#39;');
}

function replaceGeneratedSection(readme, content) {
	const startIndex = readme.indexOf(startMarker);
	const endIndex = readme.indexOf(endMarker);

	if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
		throw new Error(`README.md must contain ${startMarker} followed by ${endMarker}.`);
	}
	if (
		readme.indexOf(startMarker, startIndex + startMarker.length) !== -1 ||
		readme.indexOf(endMarker, endIndex + endMarker.length) !== -1
	) {
		throw new Error('README.md contains duplicate contributor grid markers.');
	}

	const before = readme.slice(0, startIndex + startMarker.length);
	const after = readme.slice(endIndex);
	return `${before}\n${content}\n${after}`;
}
