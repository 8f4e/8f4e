import type { Dx7Patch } from './decode.ts';

export interface BlockOptions {
	x?: number;
	y?: number;
	source?: string;
}

/** Routing that needs a voice other than the algorithm-5 example. */
export function getUnsupportedSettings(patch: Dx7Patch): string[] {
	return patch.algorithm === 5 ? [] : [`algorithm ${patch.algorithm} routing`];
}

export function toConstantsBlock(patch: Dx7Patch, { x = 0, y = 0, source }: BlockOptions = {}): string {
	// Patch names are untrusted MIDI data; keep them within a single comment.
	const comment = (text: string) => text.replace(/[^\x20-\x7e]/g, '?');
	const lines = ['constants preset', `; @pos ${x} ${y}`, `; ${comment(patch.name)}`, '; @hide'];
	if (source) lines.push(`; Source: ${comment(source)}`);
	lines.push('; Generated by tools/dx7-to-8f4e.', '; Move furthest right to select this preset.');
	const unsupported = getUnsupportedSettings(patch);
	if (unsupported.length) {
		lines.push('; Preserved settings not applied by dx7Algorithm5:');
		lines.push(...unsupported.map(setting => `; ${setting}.`));
	}
	const constant = (name: string, value: number | string) => lines.push(`const ${name} ${value}`);
	const float = (value: number) => value.toFixed(9);
	lines.push('');
	constant('ALGORITHM', patch.algorithm);
	constant('OSC_KEY_SYNC', patch.keySync);
	constant('FEEDBACK', patch.feedback);
	constant('TRANSPOSE_SEMITONES', patch.transpose);
	patch.pitchRates.forEach((value, index) => constant(`PITCH_RATE${index + 1}`, value));
	patch.pitchLevels.forEach((value, index) => constant(`PITCH_LEVEL${index + 1}`, value));
	for (const [name, value] of [
		['LFO_SPEED', patch.lfoSpeed],
		['LFO_DELAY', patch.lfoDelay],
		['LFO_PITCH_DEPTH', patch.lfoPitchDepth],
		['LFO_AMPLITUDE_DEPTH', patch.lfoAmplitudeDepth],
		['LFO_SYNC', patch.lfoSync],
		['LFO_WAVE', patch.lfoWave],
		['PITCH_MOD_SENSITIVITY', patch.pitchModSensitivity],
	] as const)
		constant(name, value);

	patch.operators.forEach((op, index) => {
		lines.push('', `; Operator ${index + 1}.`);
		const prefix = `OP${index + 1}_`;
		// Match the existing example's tuning convention. Fixed frequencies do not transpose.
		// Detune calibration: google/music-synthesizer-for-android, dx7note.cc, osc_freq.
		const detune = 2 ** ((12606 * (op.detune - 7)) / 16777216);
		const transpose = 2 ** (patch.transpose / 12);
		const ratio = op.mode === 0 ? (op.coarse || 0.5) * (1 + op.fine / 100) * detune * transpose : 0;
		const fixedHz =
			op.mode === 1
				? 10 ** ((op.coarse & 3) + op.fine / 100) * 2 ** ((13457 * Math.max(0, op.detune - 7)) / 16777216)
				: 0;
		lines.push('; RATIO includes transpose, fine tuning and detune.');
		constant(`${prefix}RATIO`, float(ratio));
		constant(`${prefix}FIXED_HZ`, float(fixedHz));
		// The example normalizes each envelope and uses this linear operator gain.
		constant(`${prefix}GAIN`, (op.outputLevel / 100).toFixed(2));
		op.rates.forEach((value, stage) => constant(`${prefix}RATE${stage + 1}`, value));
		op.levels.forEach((value, stage) => constant(`${prefix}LEVEL${stage + 1}`, value));
		for (const [name, value] of [
			['RATE_SCALING', op.rateScaling],
			['OUTPUT_LEVEL', op.outputLevel],
			['VELOCITY_SENSITIVITY', op.velocitySensitivity],
			['BREAKPOINT', op.breakpoint],
			['LEFT_DEPTH', op.leftDepth],
			['RIGHT_DEPTH', op.rightDepth],
			['LEFT_CURVE', op.leftCurve],
			['RIGHT_CURVE', op.rightCurve],
			['AMP_MOD_SENSITIVITY', op.ampModSensitivity],
			['MODE', op.mode],
			['COARSE', op.coarse],
			['FINE', op.fine],
			['DETUNE', op.detune],
		] as const)
			constant(prefix + name, value);
	});
	if (patch.algorithm === 5) {
		lines.push('');
		constant('MIX1_GAIN', '0.5');
		constant('MIX3_GAIN', '0.5');
		constant('MIX5_GAIN', '0.5');
		constant('OUTPUT_GAIN', '0.65');
	}
	return `${lines.join('\n')}\nconstantsEnd\n`;
}
