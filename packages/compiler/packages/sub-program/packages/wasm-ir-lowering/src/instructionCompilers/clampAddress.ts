import type { CodegenContext, InstructionCompiler, MemoryAddressRange } from '@8f4e/language-spec';
import { clampAddressByteCode, rangeUpperByteAddressCode } from './utils/addressClamp';
import { linearLastValidStartAddress } from './utils/memoryAccessGuard';
import { saveByteCode } from './utils/saveByteCode';

function clampToRange(context: CodegenContext, range: MemoryAddressRange, accessByteWidth: number) {
	return saveByteCode(
		context,
		clampAddressByteCode(context, range.byteAddress, rangeUpperByteAddressCode(range, accessByteWidth))
	);
}

/**
 * Clamps the top stack address to its inferred safe or explicit clamp range.
 *
 * @param _line - Clamp instruction line.
 * @param context - Compilation context receiving the generated bytecode.
 * @returns The updated compilation context.
 */
export const clampAddress: InstructionCompiler = (_line, context, facts) => {
	const { accessByteWidth, range } = facts.clamp!;

	return clampToRange(context, range!, accessByteWidth);
};

/**
 * Clamps the top stack address to the active module's memory range.
 *
 * @param _line - Clamp instruction line.
 * @param context - Compilation context for the active module.
 * @returns The updated compilation context.
 */
export const clampModuleAddress: InstructionCompiler = (_line, context, facts) => {
	const { accessByteWidth, range } = facts.clamp!;

	return clampToRange(context, range!, accessByteWidth);
};

/**
 * Clamps the top stack address to the whole linear memory range for its access width.
 *
 * @param _line - Clamp instruction line.
 * @param context - Compilation context receiving the generated bytecode.
 * @returns The updated compilation context.
 */
export const clampGlobalAddress: InstructionCompiler = (_line, context, facts) => {
	const { accessByteWidth } = facts.clamp!;

	return saveByteCode(context, clampAddressByteCode(context, 0, linearLastValidStartAddress(accessByteWidth)));
};
